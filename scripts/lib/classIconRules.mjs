/**
 * Which icon each engine class gets, and in what colour: the rules
 * `build-class-icons.mjs` applies to the catalogue.
 *
 * A class's **purpose** is its colour. It is an explicit entry in `ANCESTORS`
 * for the class or its nearest ancestor that has one, else the first `NAMES`
 * pattern its name matches, else "studio". Its **glyph** is an explicit entry
 * in `GLYPHS`, else the first `TOKENS` pattern its name matches, else its
 * purpose's glyph.
 *
 * Glyph names are Material Symbols (Apache-2.0). `drawn:<name>` is one of
 * Roswaal's own drawings in `assets/`, and `c:<name>` one of the composites
 * `build-class-icons.mjs` builds from Material glyphs and marks of Roswaal's
 * own. Each was chosen from words in the class's Creator Docs summary, never
 * from Roblox's own icons.
 */

