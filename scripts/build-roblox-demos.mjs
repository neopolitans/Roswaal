/**
 * Takes the Roblox demo project's graphs into a module the documentation draws.
 *
 * The opposite direction to `build-lune-demo.mjs`, and for the opposite reason.
 * The Lune demos were authored as pictures and turned into a project; the
 * Roblox demo has been a project since long before there was a page about it,
 * and it is the one `roswaal init` points at and the daemon's own tests open.
 * So the project is the source and the page reads from it.
 *
 * That matters more here than it would elsewhere: the introduction panel offers
 * this demo as something to take a copy of, and a page describing a different
 * version of what you are about to copy would be worse than no page at all.
 *
 *     node scripts/build-roblox-demos.mjs
 *
 * `tests/robloxdemos.test.ts` checks the generated module still matches what is
 * on disk, so editing the demo and not regenerating fails rather than leaving
 * the page describing the version before.
 */

import { readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const PROJECT = join(root, "examples", "demo", ".roswaal", "scripts");
const OUT = join(root, "src", "core", "docs", "robloxDemos.ts");

/** Which graphs the page shows, and where each one lives in the project. */
const GRAPHS = [
	["greeter", "ReplicatedStorage/Shared/Greeter.nodescript"],
	["main", "ServerScriptService/Source/Main.nodescript"],
];

const MAP = "Game.nodemap";

const HEADER = `/**
 * The Roblox demo project's graphs and its node map, as data.
 *
 * Generated by \`scripts/build-roblox-demos.mjs\` — do not edit by hand. These
 * are the files in \`examples/demo\`, which is the project the panel offers to
 * take a copy of: what the page shows and what the copy contains are the same
 * thing, and they would not stay that way if this were kept by hand.
 *
 * Cast rather than annotated, because these are JSON: every string in them
 * widens away from the literal types the schema's unions are built on. What
 * checks them is behaviour — \`tests/robloxdemos.test.ts\` compiles them and
 * compares them against the files on disk.
 */

import type { NodeMap } from "../nodemap.js";
import type { NodeScript } from "../schema.js";
`;

/** JSON as a TypeScript literal, indented to sit inside a declaration. */
function literal(value) {
	const tab = String.fromCharCode(9);
	const newline = String.fromCharCode(10);
	return JSON.stringify(value, null, tab).split(newline).join(newline + tab);
}

const scripts = {};
for (const [id, rel] of GRAPHS) {
	scripts[id] = JSON.parse(await readFile(join(PROJECT, rel), "utf8"));
}
const map = JSON.parse(await readFile(join(PROJECT, MAP), "utf8"));

const newline = String.fromCharCode(10);
const tab = String.fromCharCode(9);

const body = [
	HEADER,
	"/** Keyed by the name the page uses, not by the path on disk. */",
	"export const ROBLOX_DEMO_GRAPHS =",
	`${tab}${literal(scripts)} as unknown as Record<string, NodeScript>;`,
	"",
	"/** The demo's node map, drawn on the page in the editor that edits it. */",
	"export const ROBLOX_DEMO_MAP =",
	`${tab}${literal(map)} as unknown as NodeMap;`,
	"",
].join(newline);

await writeFile(OUT, body, "utf8");
console.log(`roblox demos: ${GRAPHS.length} graphs and a map -> src/core/docs/robloxDemos.ts`);
