export type IconName = keyof typeof ICONS;

export interface IconProps {
	name: IconName;
	/** Pixel size; the glyph is square. */
	size?: number;
	className?: string;
	/** Rotation in degrees, for the chevron. */
	rotate?: number;
	title?: string;
}

export function Icon({ name, size = 16, className, rotate, title }: IconProps) {
	return (
		<svg
			className={className ? `icon ${className}` : "icon"}
			viewBox={VIEW_BOX}
			width={size}
			height={size}
			aria-hidden={title ? undefined : true}
			style={rotate ? { transform: `rotate(${rotate}deg)` } : undefined}
		>
			{title && <title>{title}</title>}
			{STROKED[name] ? (
				<path
					d={ICONS[name]}
					fill="none"
					stroke="currentColor"
					strokeWidth={STROKED[name]}
					strokeLinecap="round"
				/>
			) : (
				<path d={ICONS[name]} fill="currentColor" />
			)}
		</svg>
	);
}

/** Glyphs drawn as a centre line, by stroke width in the 960 grid. */
const STROKED: Partial<Record<IconName, number>> = { function: 80 };
