/** A BrickColor number's colour, 0 to 1 a channel; undefined for a number the table has not. */
export function brickColorRgb(n: number): [number, number, number] | undefined {
	const hex = BRICK_COLORS[n];
	if (hex === undefined) return undefined;
	return [((hex >> 16) & 255) / 255, ((hex >> 8) & 255) / 255, (hex & 255) / 255];
}
