/**
 * What a new instance of a common class starts with: every property Studio
 * saves for a fresh one, so an instance added to a place that already holds
 * its class has a real value in each of that class's columns -- a Part
 * 4 by 1 by 2 studs of grey plastic, not one of nothing.
 *
 * **Written here, not read from Roblox's files.** The values are the ones a
 * fresh instance of each class starts with in Studio, observed by creating one
 * of each and saving it; class, property and enum names are Roblox's API. A
 * value shared by every listed subclass of a base sits on the base. Name, the
 * two ids and a script's ScriptGuid are made new for each instance and are not
 * here.
 *
 * A class not listed takes its bases' values here and, for the rest, those of
 * an instance of its class in the place (`instances.ts`); where the place has
 * none, Studio fills in the rest when it opens the file.
 */

import type { ColorKeypoint, NumberKeypoint, Prop } from "./dom.js";

const utf8 = new TextEncoder();
const text = (v: string): Prop => ({ type: "String", value: utf8.encode(v) });
const shared = (v: string): Prop => ({ type: "SharedString", value: utf8.encode(v) });
const bool = (value: boolean): Prop => ({ type: "Bool", value });
const int = (value: number): Prop => ({ type: "Int32", value });
const int64 = (value: bigint): Prop => ({ type: "Int64", value });
const float = (value: number): Prop => ({ type: "Float32", value });
const double = (value: number): Prop => ({ type: "Float64", value });
const token = (value: number): Prop => ({ type: "Enum", value });
const brick = (value: number): Prop => ({ type: "BrickColor", value });
const color = (r: number, g: number, b: number): Prop => ({ type: "Color3", value: [r, g, b] });
const color8 = (r: number, g: number, b: number): Prop => ({
	type: "Color3uint8",
	value: [r, g, b],
});
const vector2 = (...value: number[]): Prop => ({ type: "Vector2", value });
const vector3 = (...value: number[]): Prop => ({ type: "Vector3", value });
const uDim = (...value: number[]): Prop => ({ type: "UDim", value });
const uDim2 = (...value: number[]): Prop => ({ type: "UDim2", value });
const numberRange = (...value: number[]): Prop => ({ type: "NumberRange", value });
const rect = (...value: number[]): Prop => ({ type: "Rect", value });
const cframe = (position: number[], rotation: number[]): Prop => ({
	type: "CFrame",
	value: { position, rotation },
});
const noCFrame = (): Prop => ({ type: "OptionalCFrame", value: null });
const none = (): Prop => ({ type: "Ref", value: null });
const capabilities = (value: bigint): Prop => ({ type: "SecurityCapabilities", value });
const font = (family: string, weight: number, style: number, cachedFaceId: string): Prop => ({
	type: "Font",
	value: { family, weight, style, cachedFaceId },
});
const physics = (flag: number, ...values: number[]): Prop => ({
	type: "PhysicalProperties",
	value: { flag, values },
});
const numbers = (...value: NumberKeypoint[]): Prop => ({ type: "NumberSequence", value });
const colors = (...value: ColorKeypoint[]): Prop => ({ type: "ColorSequence", value });
const noContent = (): Prop => ({ type: "Content", value: { source: 0 } });

