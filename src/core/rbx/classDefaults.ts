/** The classes with defaults here, for the editor's list of what to add. */
export const DEFAULTED_CLASSES: readonly string[] = Object.keys(CLASSES);

/**
 * Every property a fresh instance of `className` saves, by name, or undefined
 * for a class not listed. `chain` is the class and its ancestors, nearest
 * first (`classChain`).
 */
export function classDefaults(
	className: string,
	chain: readonly string[],
): Map<string, Prop> | undefined {
	const own = CLASSES[className];
	if (!own) return undefined;
	const out = baseDefaults(chain);
	for (const [name, prop] of Object.entries(own)) out.set(name, prop);
	return out;
}

/** What `chain`'s bases give every listed subclass: for any class, the values it shares with them. */
export function baseDefaults(chain: readonly string[]): Map<string, Prop> {
	const out = new Map<string, Prop>();
	for (const base of [...chain].reverse())
		for (const [name, prop] of Object.entries(BASES[base] ?? {})) out.set(name, prop);
	return out;
}
